# Privacy Policy

{{ $site }} is built to be privacy-friendly. We do not require an account and we never sell or share your data.

## Your files

- **Browser processing.** Many tools (for example the PDF editor, merge, split, sign, watermark and page tools) run completely inside your web browser. These files are never uploaded to our servers.
- **Server processing.** Some conversions need server software (for example Word to PDF or OCR with the server engine). Such files are uploaded over an encrypted connection, stored under a random name in a private location that is not accessible from the web, and processed automatically.
- **Automatic deletion.** Uploaded source files are deleted immediately after processing. Results are deleted shortly after you download them and in any case after {{ $ttl }} minutes. You can also delete your files at any time with the "Delete my files" button on the result screen.
- **No human access.** Nobody looks at your files. They are never used for any other purpose than the tool you selected.

## Data we collect

- **No accounts and no personal profiles.** You can use every tool without registering.
- **Technical logs.** Like every web server, ours may keep short-lived technical logs (for example error messages) to keep the service secure and working.
- **Anonymous statistics.** We may count how often each tool is used per day. These counters contain no IP addresses, no file names and no personal data.
- **Cookies.** We only use a strictly necessary session cookie that protects forms against abuse (CSRF protection). We do not use tracking cookies unless the site owner has explicitly enabled an analytics service, in which case that service is listed here.

## Translation and OCR

Translations and text recognition run on open-source engines on our own server or directly in your browser. No paid third-party cloud APIs receive your documents. When OCR runs in your browser, the OCR engine may download language data files; your document itself stays on your device.

## Contact

If you have questions about this policy, please contact the operator of this website.
