# About {{ $site }}

{{ $site }} is a free collection of PDF tools that anyone can use – without registration, subscriptions or watermarks.

## Privacy first

Whenever possible, files are processed directly in your web browser, so they never leave your device. When server processing is required, files are stored temporarily in a private location and deleted automatically.

## Built on open source

The site is powered by proven open-source software:

- **PDF.js** – rendering and text extraction in the browser
- **pdf-lib** – creating and editing PDFs in the browser
- **Fabric.js** – the interactive PDF editor
- **Tesseract** – optical character recognition (OCR)
- **qpdf, Ghostscript, Poppler and LibreOffice** – server-side processing, compression and conversions
- **LibreTranslate / Argos Translate** – open-source machine translation
- **Laravel** – the web application framework

## Free forever

All tools are free to use. The site may show a small number of advertisements to cover hosting costs.
